/**
  * @brief  双定时器同频 PWM + 硬件主从触发死区(相移) 启动
  * @note   TIM1(主) TRGO = 更新事件; TIM3(从) 触发模式 + ITR0 = TIM1_TRGO
  *         触发模式只控制"计数器启动"、不复位计数器, 因此预置
  *         CNT = ARR + 1 - N 就能得到 N 个计数的固定滞后(死区)。
  */
void MX_PWM_Start_PhaseLocked(void)
{
  TIM_MasterConfigTypeDef sMasterConfig = {0};
  TIM_SlaveConfigTypeDef  sSlaveConfig  = {0};

  /* 0) 两个定时器时基完全一致 => 输出严格同频 */
  __HAL_TIM_SET_PRESCALER(&htim1, PWM_PRESCALER);
  __HAL_TIM_SET_AUTORELOAD(&htim1, PWM_ARR_VALUE);
  __HAL_TIM_SET_PRESCALER(&htim3, PWM_PRESCALER);
  __HAL_TIM_SET_AUTORELOAD(&htim3, PWM_ARR_VALUE);

  /* 1) TIM1 的 TRGO 改成"更新事件"; MSM 必须保持 DISABLE,
   *    否则 TRGO 会被 TIM1 自己的 TRGI 门控(TIM1 的 ITR0 指向 TIM5,
   *    F103C8 上没有 TIM5), TRGO 发不出来, TIM3 永远等不到触发 */
  sMasterConfig.MasterOutputTrigger = TIM_TRGO_UPDATE;
  sMasterConfig.MasterSlaveMode     = TIM_MASTERSLAVEMODE_DISABLE;
  if (HAL_TIMEx_MasterConfigSynchronization(&htim1, &sMasterConfig) != HAL_OK)
  {
    Error_Handler();
  }

  /* 2) TIM3 配成从模式"触发模式", 触发源 ITR0 = TIM1
   *    (F103 的 TIM3 内部触发映射: ITR0=TIM1, ITR1=TIM2, ITR2=TIM5, ITR3=TIM4) */
  sSlaveConfig.SlaveMode    = TIM_SLAVEMODE_TRIGGER;
  sSlaveConfig.InputTrigger = TIM_TS_ITR0;
  if (HAL_TIM_SlaveConfigSynchro(&htim3, &sSlaveConfig) != HAL_OK)
  {
    Error_Handler();
  }

  /* 3) 先打开 TIM3 的输出通道(CH2 -> PA7)。触发模式下 HAL 不会置 CEN,
   *    计数器要等 TIM1 第一次溢出才由硬件启动, 所以此刻 TIM3 保持低电平 */
  if (HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_2) != HAL_OK)
  {
    Error_Handler();
  }

  /* 4) 预置 TIM3 的计数初值(此时 CEN=0, 写入即生效) */
  TIM3->CNT = TIM3_CNT_PRESET;

  /* 5) 最后启动 TIM1。它一溢出就会触发 TIM3, 相位从此由硬件锁定 */
  if (HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1) != HAL_OK)
  {
    Error_Handler();
  }

}

