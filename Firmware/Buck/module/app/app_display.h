#ifndef __APP_DISPLAY_H
#define __APP_DISPLAY_H

/**
 * @说明: 上电稳定延时 + 探测屏 + 首帧整屏刷新（未插屏时仅打印一行失败日志）
 * @注意: 须在 APP_TELEMETRY_Init（初始化调试输出）之后调用；内部阻塞 ≈100ms + 整屏 ≈93ms
 */
void APP_DISPLAY_Init(void);

/**
 * @说明: 主循环调用，5Hz 取数 → 变化行重绘 → 脏页下发（单次阻塞典型 25-50ms）
 * @注意: 屏掉线后每 1s 重探测，恢复时自动整屏重绘；非 ISR 上下文
 */
void APP_DISPLAY_Loop(void);

#endif /* __APP_DISPLAY_H */
