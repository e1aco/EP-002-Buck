/**
  * @brief ADC1 规则组扫描完成（DMA 搬完 2 个半字）
  * @note  顺序固定：先快照（drv_adc.c）再控制步进（app_control.c），
  *        控制步进必须读到刚更新的 s_latest，不能颠倒
  */
void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef *hadc)
{
  if (hadc->Instance == ADC1)
  {
    // TEST_TIM_Start(TEST_SLOT_ADC_ISR);   // 时序探针 [CL_TIMING_MEASURE]
    DRV_ADC_ConvCpltIsr();   /* 双通道快照 + 扫描计数（2kHz 时基） */
#if (CL_CTRL_ENABLE == 1)
    APP_CONTROL_Step();      /* PID + 软启动 + OVP → 下发 CCR1 */
#endif
    // TEST_TIM_Stop(TEST_SLOT_ADC_ISR);    // 时序探针 [CL_TIMING_MEASURE]
  }
}

